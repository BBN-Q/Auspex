"""Generate static InstrumentServer references from declarations, without device I/O."""
import argparse
import inspect
from pathlib import Path

from auspex_v2.instruments.drivers.core import Instrument, SCPIInstrument, RampCommand
from auspex_v2.instruments.drivers.registry import DRIVERS

ROOT = Path(__file__).resolve().parents[1]
PAGES = ROOT / "docs/reference/instruments"
MARKER = "<!-- Generated by utils/generate_instrument_api.py; do not edit. -->"
NAV_START = "  # BEGIN GENERATED INSTRUMENT API"
NAV_END = "  # END GENERATED INSTRUMENT API"


def prose(doc):
    """Use existing documentation without inventing missing descriptions or units."""
    return inspect.cleandoc(doc or "").replace("``", "`")


def origin(driver, name, member):
    for base in driver.__mro__:
        if vars(base).get(name) is member:
            return f"{base.__module__}.{base.__name__}"
    raise ValueError(f"No declaring class for {driver.__name__}.{name}")


def declaration(command):
    """Reconstruct explicit command metadata, not source text or runtime readbacks."""
    fields = {"get_string": command.get_string, "set_string": command.set_string}
    for name in ("value_map", "value_range", "allowed_values", "aliases", "additional_args",
                 "get_delay", "set_delay"):
        value = getattr(command, name)
        if value is not None and value != () and value != 0:
            fields[name] = value
    if isinstance(command, RampCommand):
        fields.update(increment=command.increment, pause=command.pause)
    return (type(command).__name__ + "(\n" +
            "".join(f"    {name}={value!r},\n" for name, value in fields.items()) + ")")


def driver_page(driver):
    """List the effective admitted API, including inherited members and caveats."""
    name = driver.__name__
    lines = [MARKER, f"# {name}", "[Driver index](index.md)",
             f"**KIND:** `{driver.KIND}`",
             f"**Experimental:** {'yes — not hardware-validated' if driver.EXPERIMENTAL else 'not marked experimental'}",
             "The experimental marker is declaration metadata, not a safety certification.",
             "## Model notes"]
    for base in driver.__mro__:
        if base in (Instrument, SCPIInstrument, object):
            continue
        doc = prose(vars(base).get("__doc__"))
        if doc:
            lines.extend([f"### {base.__name__}", doc])
    for field in ("IDN_STRING", "ports"):
        value = getattr(driver, field, None)
        if value is not None:
            lines.append(f"**{field}:** `{value!r}`")
    lines.extend(["## Settings (GET / SET)",
                  "Access and constraints below are declared in Python. Missing limits or units "
                  "are not evidence of unrestricted hardware operation. See the "
                  "[access conventions](index.md#access-conventions)."])
    settings = {**driver.commands, **driver.properties}
    if not settings:
        lines.append("No declared settings.")
    for setting, member in sorted(settings.items()):
        command = setting in driver.commands
        readable = member.get_string is not None if command else member.readable
        writable = member.set_string is not None if command else member.writable
        access = " / ".join(op for op, enabled in (("GET", readable), ("SET", writable)) if enabled)
        lines.extend([f"### {setting}", f"**Access:** {access}",
                      f"**Declaration:** `{type(member).__name__}`",
                      f"**Defined by:** `{origin(driver, setting, member)}`"])
        if command:
            aliases = sorted(key for key, value in driver.commands.items() if value is member and key != setting)
            if aliases:
                lines.append("**Equivalent names:** " + ", ".join(f"`{alias}`" for alias in aliases))
            if member.additional_args:
                lines.append("**Required GET/SET keyword arguments:** " +
                             ", ".join(f"`{arg}`" for arg in member.additional_args))
            lines.extend([prose(member.__doc__), "```python\n" + declaration(member) + "\n```"])
        else:
            lines.append(prose(member.__doc__))
            setter_doc = prose(member.fset.__doc__) if member.fset else ""
            if setter_doc and setter_doc != prose(member.__doc__):
                lines.extend(["**Setter notes:**", setter_doc])
    lines.append("## Operations (CALL)")
    if not driver.operations:
        lines.append("No declared operations.")
    for operation, function in sorted(driver.operations.items()):
        signature = inspect.signature(function)
        parameters = list(signature.parameters.values())
        if parameters and parameters[0].name == "self":
            signature = signature.replace(parameters=parameters[1:])
        lines.extend([f"### {operation}", f"```python\n{operation}{signature}\n```",
                      f"**Defined by:** `{origin(driver, operation, function)}`",
                      prose(function.__doc__) or "No operation docstring is declared."])
    return "\n\n".join(line for line in lines if line) + "\n"


def generated_pages():
    """Return deterministic files for exactly the server-admitted driver catalog."""
    pages = {f"{name}.md": driver_page(driver) for name, driver in sorted(DRIVERS.items())}
    index = [MARKER, "", "# Instrument driver API", "",
             "Generated from the same exported driver catalog used by InstrumentServer. "
             "Each page includes inherited settings and operations; no device is constructed or queried.",
             "", "## Drivers", ""]
    for name, driver in sorted(DRIVERS.items()):
        suffix = " — experimental" if driver.EXPERIMENTAL else ""
        index.append(f"- [{name}]({name}.md) — {driver.KIND}{suffix}")
    index.extend(["", "## Access conventions", "",
                  "- **GET / SET:** use `live.get(name, **kwargs)` / `live.set(name, value, **kwargs)`. "
                  "Simple settings also support attributes, e.g. `live.frequency` / `live.frequency = value`.",
                  "- **CALL:** use `live.call(name, *args, **kwargs)` or `live.operation(...)`. "
                  "Displayed signatures omit the driver instance (`self`).",
                  "- Command blocks show normalized `FloatCommand`, `IntCommand`, `BoolCommand`, "
                  "`StringCommand`, or `RampCommand` declarations, including SCPI templates and "
                  "declared maps/ranges/choices. A value map lists Python values as keys and wire "
                  "values as values; it can override the nominal command's readback type.",
                  "- `ManagedProperty` settings use handwritten getters/setters. Types, units, "
                  "returns and constraints are only documented where supplied by the driver. "
                  "Inspect implementation before assuming behavior not described here.",
                  "- A name beginning with `get_` does not guarantee read-only behavior: "
                  "operations may trigger acquisition or change outputs. Lifecycle/direct-use-only "
                  "methods and generated direct-driver helpers are not server CALL operations.",
                  "", "See [instrument usage and initialization caveats](../../components/instruments.md) "
                  "for ownership and model-specific precautions. "
                  "[Unavailable stubs](../../components/instruments.md#roles-and-drivers) are not "
                  "admitted drivers and intentionally have no API pages.",
                  "", "Regenerate/check using the commands in "
                  "[Maintaining the docs](../../maintaining.md#generated-instrument-reference)."])
    pages["index.md"] = "\n".join(index) + "\n"
    return pages


def navigation():
    lines = [NAV_START, '  { "Instrument driver API" = [',
             '    { "Overview" = "reference/instruments/index.md" },']
    lines.extend(f'    {{ "{name}" = "reference/instruments/{name}.md" }},' for name in sorted(DRIVERS))
    return "\n".join([*lines, "  ] },", NAV_END])


def generate(*, check=False):
    """Check or replace only generated pages/navigation; never invoke Zensical or hardware."""
    expected = {PAGES / name: content for name, content in generated_pages().items()}
    config = ROOT / "zensical.toml"
    old = config.read_text(encoding="utf8")
    start, end = old.index(NAV_START), old.index(NAV_END) + len(NAV_END)
    expected[config] = old[:start] + navigation() + old[end:]
    stale = [path for path in PAGES.glob("*.md") if path not in expected and
             path.read_text(encoding="utf8").startswith(MARKER)]
    changed = [path for path, text in expected.items()
               if not path.exists() or path.read_text(encoding="utf8") != text]
    if check:
        for path in [*changed, *stale]:
            print(f"Stale generated reference: {path.relative_to(ROOT)}")
        return not changed and not stale
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected[path], encoding="utf8")
    for path in stale:
        path.unlink()
    return True


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated docs/navigation are stale")
    raise SystemExit(0 if generate(check=parser.parse_args().check) else 1)
